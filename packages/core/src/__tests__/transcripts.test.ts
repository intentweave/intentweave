describe('Incremental Parsing', () => {
  it('should parse slice with correct offset tracking', () => {
    const fullContent = `<!-- vscode Session abc123 (2025-01-01 00:00Z) -->

_**User (2025-01-01 00:01Z)**_

First message

---

_**Assistant (gpt-4)**_

Second message

---

_**User (2025-01-01 00:02Z)**_

Third message
`;

    const fullBuffer = Buffer.from(fullContent, 'utf-8');
    
    // Parse full file first
    const fullResult = parseSpecStoryFile(fullBuffer);
    expect(fullResult.rawMessages).toHaveLength(3);
    
    // Now parse a slice starting from middle
    const sliceStart = fullResult.rawMessages[1].absHeaderOffset - 10;
    const sliceBuffer = fullBuffer.subarray(sliceStart);
    
    const sliceResult = parseSpecStorySlice(sliceBuffer, sliceStart, 'abc123');
    
    // Should find messages 2 and 3
    expect(sliceResult.rawMessages.length).toBeGreaterThanOrEqual(2);
    
    // Offsets should be absolute (not relative to slice)
    for (const msg of sliceResult.rawMessages) {
      expect(msg.absHeaderOffset).toBeGreaterThanOrEqual(sliceStart);
    }
  });
});
