describe('Heuristics', () => {
  it('should score user-like messages positively', () => {
    const result = scoreMessage('Can you help me fix this bug?');
    
    expect(result.score).toBeGreaterThan(0);
    expect(result.speaker).toBe('user');
    expect(result.signals).toContain('question');
  });

  it('should score assistant-like messages negatively', () => {
    const result = scoreMessage(`Here's the code you requested:

\`\`\`typescript
function hello() {
  console.log('Hello');
}
\`\`\`

This will print "Hello" to the console.`);
    
    expect(result.score).toBeLessThan(0);
    expect(result.speaker).toBe('assistant');
  });

  it('should detect imperatives as user messages', () => {
    const result = scoreMessage('Please create a new file called app.ts');
    
    expect(result.score).toBeGreaterThan(0);
    expect(result.signals).toContain('imperative');
  });

  it('should map speakers to message roles', () => {
    expect(speakerToMessageRole('user')).toBe('intent');
    expect(speakerToMessageRole('assistant')).toBe('implementation');
    expect(speakerToMessageRole('system')).toBe('meta');
    expect(speakerToMessageRole('tool')).toBe('runlog');
  });

  it('should strip inline role tags', () => {
    const text = '@iw role=spec This is a specification message';
    const stripped = stripInlineTags(text);
    
    expect(stripped).toBe('This is a specification message');
  });
});

